const fs = require('fs'), path = require('path');
const dir = process.argv[2];
const cfg = JSON.parse(fs.readFileSync(path.join(dir,'config.json'),'utf8'));
const ID = cfg.INJECT_DATA;
const extra = [];
const sys = ID.apiGetSystemStatus.data.data.homeGetSysInfo;
extra.push('## Access / safety switches');
extra.push('nowallet = ' + JSON.stringify(sys.nowallet));
extra.push('loginRegister = ' + JSON.stringify(sys.loginRegister));
extra.push('registermode = ' + sys.registermode);
extra.push('site_status = ' + JSON.stringify(sys.site_status));
extra.push('token = ' + JSON.stringify(sys.token));
extra.push('largeAmountRange = ' + JSON.stringify(sys.largeAmountRange));
extra.push('largeAmountMustBind = ' + JSON.stringify(sys.largeAmountMustBind));
extra.push('legal_config_location_detection = ' + JSON.stringify(sys.legal_config_location_detection));
extra.push('legal_config_login_status = ' + JSON.stringify(sys.legal_config_login_status));
extra.push('loginPasswdStrengthDetectSwitch = ' + JSON.stringify(sys.loginPasswdStrengthDetectSwitch));
extra.push('');
extra.push('## Layout arrays');
const ld = ID.apiGetOptimizationSiteConfigV2.data.data.layoutDesign;
extra.push('navType=' + ld.navType + ' banner=' + ld.banner + ' layouts=' + ld.layouts);
extra.push('');
extra.push('## Game providers (cate slots)');
const lst = ID.apiGetGameCateExtLinkList.data.data;
const provs = [];
(function walk(o){
  if (!o || typeof o !== 'object') return;
  if (typeof o.t10 === 'string' && typeof o.t9 === 'number') provs.push(`${o.t9}=${o.t10} (${o.t15})`);
  for (const v of Object.values(o)) walk(v);
})(lst);
extra.push([...new Set(provs)].join('; '));
extra.push('');
extra.push('## apiGetHotGameList count');
const hg = ID.apiGetHotGameList;
extra.push(JSON.stringify(hg).slice(0,600));
fs.appendFileSync(path.join(dir,'notes.md'), extra.join('\n')+'\n');
console.log(extra.join('\n'));
